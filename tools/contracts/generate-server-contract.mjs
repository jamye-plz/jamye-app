import { createHash } from "node:crypto";
import { mkdir, readFile, rename, rm, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

const GENERATED_FILE_NAME = "server-api.ts";
const LOCK_FILE_NAME = "contract.lock";
const OPENAPI_FILE_NAME = "openapi.json";
const GENERATOR_IDENTITY = "openapi-typescript@7.13.0";
// M6 established the initial runtime schema closure (auth + health + user
// profile). M7 extends it with the groups/membership/invitations surface
// (G1-G8, I1-I2) that was already present in the imported OpenAPI snapshot;
// see contracts/server/intake.json for the frozen intake-time closure this
// milestone deliberately grows beyond. M8 extends it again with the chat
// surface (C1-C4), including the additive C3 message_id-or-cursor read anchor.
// M9 task-1 extends it again with the delta-recovery surface (S1 GET events,
// R1 POST realtime ticket); the realtime WebSocket frame/protocol schemas
// are not OpenAPI operations and are validated separately from the
// selectively vendored contracts/server/realtime/*.json artifacts.
const SCHEMA_CLOSURE_OPERATION_IDS = Object.freeze([
  "A1",
  "A2",
  "A3",
  "A4",
  "A5",
  "H1",
  "H2",
  "U1",
  "G1",
  "G2",
  "G3",
  "G4",
  "G5",
  "G6",
  "G7",
  "G8",
  "I1",
  "I2",
  "C1",
  "C2",
  "C3",
  "C4",
  "S1",
  "R1",
]);

function isRecord(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function normalizeJson(value) {
  if (Array.isArray(value)) return value.map(normalizeJson);
  if (!isRecord(value)) return value;

  return Object.fromEntries(
    Object.keys(value)
      .sort()
      .map((key) => [key, normalizeJson(value[key])]),
  );
}

export function canonicalizeJson(value) {
  return `${JSON.stringify(normalizeJson(value), null, 2)}\n`;
}

export function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

function requireNonEmptyString(value, label) {
  if (typeof value !== "string" || value.length === 0) {
    throw new Error(`${label} must be a non-empty string.`);
  }
  return value;
}

async function writeStagedFiles(files) {
  const stagedFiles = files.map(({ path, contents }) => ({
    contents,
    path,
    temporaryPath: `${path}.tmp-${process.pid}-${Math.random().toString(36).slice(2)}`,
  }));

  try {
    await Promise.all(
      stagedFiles.map(({ contents, temporaryPath }) =>
        writeFile(temporaryPath, contents, "utf8"),
      ),
    );
    await Promise.all(
      stagedFiles.map(({ path, temporaryPath }) => rename(temporaryPath, path)),
    );
  } catch (error) {
    await Promise.all(
      stagedFiles.map(({ temporaryPath }) =>
        rm(temporaryPath, { force: true }),
      ),
    );
    throw error;
  }
}

/**
 * Deterministically generates the full server OpenAPI TypeScript type
 * boundary from the local contracts/server/openapi.json snapshot (an
 * already-vetted intake artifact; this step never reads the sibling
 * jamye-server checkout). Full document types are generated, but the
 * contract.lock only records the current runtime schema closure
 * (SCHEMA_CLOSURE_OPERATION_IDS above) so later milestones extending the
 * closure are explicit.
 */
async function buildServerContractArtifacts({
  contractRoot,
  generatedDirectory,
}) {
  const resolvedContractRoot = resolve(contractRoot);
  const openapiPath = join(resolvedContractRoot, OPENAPI_FILE_NAME);
  const openapiBytes = await readFile(openapiPath);
  const openapi = JSON.parse(openapiBytes.toString("utf8"));
  const contractVersion = requireNonEmptyString(
    openapi?.info?.version,
    "openapi.info.version",
  );

  const generatedAst = await openapiTS(pathToFileURL(openapiPath), {
    emptyObjectsUnknown: true,
  });
  const generatedSource = [
    "// Generated by openapi-typescript. Do not edit.",
    astToString(generatedAst).trimEnd(),
    "",
  ].join("\n");

  const lock = normalizeJson({
    contract_version: contractVersion,
    generated_sha256: sha256(generatedSource),
    generator_identity: GENERATOR_IDENTITY,
    schema_closure_operation_ids: [...SCHEMA_CLOSURE_OPERATION_IDS],
    source_sha256: sha256(openapiBytes),
  });

  return {
    generatedDirectory: resolve(generatedDirectory),
    generatedSource,
    lock,
    resolvedContractRoot,
  };
}

export async function generateServerContract({
  contractRoot,
  generatedDirectory,
}) {
  const artifacts = await buildServerContractArtifacts({
    contractRoot,
    generatedDirectory,
  });

  await mkdir(artifacts.generatedDirectory, { recursive: true });
  await writeStagedFiles([
    {
      contents: canonicalizeJson(artifacts.lock),
      path: join(artifacts.resolvedContractRoot, LOCK_FILE_NAME),
    },
    {
      contents: artifacts.generatedSource,
      path: join(artifacts.generatedDirectory, GENERATED_FILE_NAME),
    },
  ]);

  return { generatedFiles: [GENERATED_FILE_NAME], lock: artifacts.lock };
}

export async function buildServerContractArtifactsForCheck(input) {
  return buildServerContractArtifacts(input);
}

function defaultPaths() {
  const repositoryRoot = resolve(
    fileURLToPath(new URL("../..", import.meta.url)),
  );
  return {
    contractRoot: join(repositoryRoot, "contracts/server"),
    generatedDirectory: join(
      repositoryRoot,
      "src/core/contracts/generated/server",
    ),
  };
}

if (
  process.argv[1] &&
  pathToFileURL(resolve(process.argv[1])).href === import.meta.url
) {
  const result = await generateServerContract(defaultPaths());
  process.stdout.write(`${canonicalizeJson(result)}`);
}
